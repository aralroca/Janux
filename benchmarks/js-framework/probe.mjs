import { chromium } from 'playwright';
const b = await chromium.launch({ headless: true });
const p = await b.newPage();
await p.goto('http://localhost:5176/', { waitUntil: 'load' });
await p.waitForSelector('#run');
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const click = (s) => p.evaluate(async (x) => { const el = document.querySelector(x); const t0=performance.now(); el.click(); if (window.__benchFlush) await window.__benchFlush(); return performance.now()-t0; }, s);
await click('#run'); await sleep(100);
for (let i=0;i<10;i++) await click('#rotateb');
await sleep(100);
const client = await p.context().newCDPSession(p);
await client.send('Profiler.enable');
await client.send('Profiler.setSamplingInterval', { interval: 50 });
await client.send('Profiler.start');
let tot = 0;
for (let i=0;i<40;i++) tot += await click('#rotateb');
const { profile } = await client.send('Profiler.stop');
console.log('avg rotateb', (tot/40).toFixed(2), 'ms');
const byId = new Map(profile.nodes.map((n) => [n.id, n]));
const self = new Map();
for (const id of profile.samples || []) { const n = byId.get(id); if (!n) continue; const k = `${n.callFrame.functionName || '(anon)'}:${n.callFrame.lineNumber}`; self.set(k, (self.get(k)||0)+1); }
const total = (profile.samples||[]).length;
console.log('samples', total);
[...self.entries()].sort((a,b)=>b[1]-a[1]).slice(0,22).forEach(([k,v])=>console.log((v/total*100).toFixed(1)+'%', v, k));
await b.close();
